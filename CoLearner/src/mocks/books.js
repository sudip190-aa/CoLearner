const cover = (seed) =>
  `https://images.unsplash.com/${seed}?auto=format&fit=crop&w=720&q=80`

const makeChapter = (order, title, focus, estMinutes) => ({
  order,
  title,
  estMinutes,
  paragraphs: [
    `${title} begins with a practical question: how do we make ${focus} easier to reason about when the requirements are still changing? The answer is not a clever trick. It is a clear model of the problem, the people affected by it, and the trade-offs we are willing to make.`,
    `A useful way to study ${focus} is to start with a small example and follow it all the way through the system. Write down what you expected to happen, observe what actually happened, and name the boundary where those two stories diverged. That habit turns vague frustration into evidence.`,
    `Good teams make this work visible. They keep decisions close to the code, explain why an approach was chosen, and leave enough context for the next person to continue. When the example becomes more complicated, the explanation should become more precise rather than more mysterious.`,
    `By the end of this chapter, you should be able to describe ${focus} in your own words, sketch the important states, and choose one small experiment that will teach you something. The goal is durable understanding, not a perfect answer on the first attempt.`,
  ],
})

const makeBook = (
  id,
  title,
  slug,
  author,
  description,
  category,
  difficulty,
  estMinutes,
  tags,
  seed,
  chapters,
) => ({
  id,
  title,
  slug,
  author,
  cover: cover(seed),
  description,
  category,
  difficulty,
  estMinutes,
  tags,
  chapters: chapters.map((chapter, index) =>
    makeChapter(index + 1, chapter[0], chapter[1], chapter[2]),
  ),
})

