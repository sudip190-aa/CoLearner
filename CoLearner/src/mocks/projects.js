import { users } from './users.js'

const statuses = ['todo', 'in_progress', 'review', 'done']
const priorities = ['low', 'medium', 'high']

const makeTasks = (projectId, titles, assignees, startDate) =>
  titles.map((title, index) => ({
    id: `${projectId}_task_${String(index + 1).padStart(2, '0')}`,
    title,
    status: statuses[index % statuses.length],
    assignee: assignees[index % assignees.length].id,
    priority: priorities[(index + 1) % priorities.length],
    dueDate: `${startDate.slice(0, 8)}${String(12 + (index % 16)).padStart(2, '0')}T17:00:00Z`,
  }))

const makeMilestones = (projectId, names) =>
  names.map((name, index) => ({
    id: `${projectId}_milestone_${index + 1}`,
    title: name,
    status: index === 0 ? 'complete' : index === 1 ? 'in_progress' : 'upcoming',
    dueDate: `2026-${String(9 + Math.floor(index / 2)).padStart(2, '0')}-${String(18 + index * 4).padStart(2, '0')}T17:00:00Z`,
  }))

const makeUpdates = (projectId, updates, authorIds) =>
  updates.map((body, index) => ({
    id: `${projectId}_update_${index + 1}`,
    author: authorIds[index % authorIds.length],
    body,
    createdAt: `2026-09-${String(12 + index * 2).padStart(2, '0')}T${String(10 + index).padStart(2, '0')}:30:00Z`,
  }))

